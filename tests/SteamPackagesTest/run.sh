#!/bin/bash
# Steam's update fetched ahead: which packages a manifest names (against what Steam asked for), and how they go into place:
# tests/SteamPackagesTest/run.sh
set -euo pipefail
cd "$(dirname "$0")/../.."
# shellcheck source=scripts/sdk-lib.sh
. scripts/sdk-lib.sh && nightforge_pick_sdk
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT  # the test program goes with it
OUT="$WORK/steam-packages-test"
